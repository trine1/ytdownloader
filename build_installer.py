#!/usr/bin/env python3
"""Build the distribution-neutral standalone Linux installer for ytdownloader.

The result is a single self-extracting POSIX-ish bash script:

    ytdownloader-<version>-linux-installer.sh

Running it (bash <script>) will:
    * install the app into ~/.local/share/ytdownloader (configurable --prefix)
    * create an isolated venv there and pip-install PyQt6 + yt-dlp from
      PyPI (network required at install time only)
    * if ffmpeg is missing system-wide, optionally download a static build
      into the app's private bin dir (skipped with --no-ffmpeg)
    * create <prefix>/bin/ytdownloader launcher and a desktop entry
    * support --uninstall (which keeps the user's state.json) and --help

The script therefore has no distro-specific dependencies (no apt/dnf needed),
unlike the Debian package.
"""

from __future__ import annotations

import base64
import io
import os
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAYLOAD_MARKER = "__YTD_PAYLOAD_BELOW__"


def read_version() -> str:
    for line in (ROOT / "pyproject.toml").read_text(encoding="utf-8").splitlines():
        if line.startswith("version"):
            return line.split("=", 1)[1].strip().strip('"')
    raise RuntimeError("could not determine version from pyproject.toml")


def build_payload() -> bytes:
    """Tarball with the source needed to pip-install the app."""
    buf = io.BytesIO()
    pkg = ROOT / "yt_downloader"
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        tar.add((ROOT / "pyproject.toml").resolve(), arcname="pyproject.toml")
        tar.add((ROOT / "yt_downloader.desktop").resolve(), arcname="yt_downloader.desktop")
        for py_file in sorted(pkg.glob("*.py")):
            tar.add(py_file.resolve(), arcname=f"yt_downloader/{py_file.name}")
    return buf.getvalue()


INSTALLER_TEMPLATE = r'''#!/usr/bin/env bash
# ytdownloader @VERSION@ - self-extracting, distribution-neutral installer.
# Generated by build_installer.py; source: https://github.com/trine1/ytdownloader
set -u

APP_ID="ytdownloader"
VERSION="@VERSION@"
DEFAULT_PREFIX="$HOME/.local"
WITH_FFMPEG_DL="yes"
ACTION="install"

die() { echo "Error: $*" >&2; exit 1; }
info() { echo "[ytdownloader-installer] $*"; }

usage() {
cat <<USAGE
Usage: bash $0 [options]

Options:
  --prefix DIR     install under DIR (default: $HOME/.local)
  --no-ffmpeg      do not auto-download a static ffmpeg when none is found
  --uninstall      remove the installed app, launcher, and desktop entry
                   (your saved state in <prefix>/share/ytdownloader/state.json
                   is kept)
  --help           show this help and exit

This installer creates an isolated environment under
  <prefix>/share/ytdownloader
installs PyQt6 and yt-dlp from PyPI into it (internet needed once),
and writes a launcher to <prefix>/bin/ytdownloader.
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) PREFIX="${2:-}"; shift 2 ;;
        --no-ffmpeg) WITH_FFMPEG_DL="no"; shift ;;
        --uninstall) ACTION="uninstall"; shift ;;
        --help|-h) usage; exit 0 ;;
        *) usage; echo; die "unknown option: $1" ;;
    esac
done
PREFIX="${PREFIX:-$DEFAULT_PREFIX}"

SHARE_DIR="$PREFIX/share/ytdownloader"
BIN_DIR="$PREFIX/bin"
LAUNCHER="$BIN_DIR/$APP_ID"
DESKTOP_DIR="$PREFIX/share/applications"
DESKTOP_FILE="$DESKTOP_DIR/$APP_ID.desktop"

if [ "$ACTION" = "uninstall" ]; then
    info "Removing $SHARE_DIR, $LAUNCHER, $DESKTOP_FILE"
    # The app's state file lives *inside* SHARE_DIR (it is the app's XDG
    # data dir): the queue, settings and notification preferences. Save it
    # aside first — uninstalling the app must not delete user data.
    STATE_KEEP=""
    if [ -f "$SHARE_DIR/state.json" ]; then
        STATE_KEEP="$(mktemp -d)" || STATE_KEEP=""
        [ -n "$STATE_KEEP" ] && cp -p "$SHARE_DIR/state.json" "$STATE_KEEP/state.json" \
            || STATE_KEEP=""
    fi
    rm -rf "$SHARE_DIR"
    rm -f "$LAUNCHER" "$DESKTOP_FILE"
    if [ -n "$STATE_KEEP" ] && [ -f "$STATE_KEEP/state.json" ]; then
        mkdir -p "$SHARE_DIR"
        mv "$STATE_KEEP/state.json" "$SHARE_DIR/state.json"
        rmdir "$STATE_KEEP" 2>/dev/null || true
        info "   kept your state: $SHARE_DIR/state.json"
    fi
    info "Uninstall complete."
    exit 0
fi

# ---------------------------------------------------------------- python
PY=""
for cand in python3 python3.14 python3.13 python3.12 python3.11 python3.10; do
    if command -v "$cand" >/dev/null 2>&1; then
        if "$cand" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' 2>/dev/null; then
            PY="$cand"; break
        fi
    fi
done
[ -n "$PY" ] || die "Python 3.10+ (python3) is required."

# ---------------------------------------------------------------- extract
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
LINE="$(awk -v m="__YTD_PAYLOAD_BELOW__" '$0 == m {print NR + 1; exit}' "$0")"
[ -n "$LINE" ] || die "payload marker not found"
info "Extracting application payload ..."
tail -n +"$LINE" "$0" | base64 -d | tar -xzf - -C "$WORK" || die "payload extraction failed"

# ---------------------------------------------------------------- venv
info "Creating isolated environment (python: $($PY -V 2>&1)) ..."
if ! "$PY" -m venv "$SHARE_DIR/venv" 2>"$WORK/venv.err"; then
    info "plain venv failed; retrying without pip (missing python3-venv?) ..."
    if ! "$PY" -m venv --without-pip "$SHARE_DIR/venv"; then
        cat "$WORK/venv.err" >&2
        die "cannot create a virtual environment"
    fi
    for getter in curl wget; do
        command -v "$getter" >/dev/null 2>&1 || continue
        case "$getter" in
            curl) curl -fsSL https://bootstrap.pypa.io/get-pip.py -o "$WORK/get-pip.py" ;;
            wget) wget -qO "$WORK/get-pip.py" https://bootstrap.pypa.io/get-pip.py ;;
        esac
        "$SHARE_DIR/venv/bin/python" "$WORK/get-pip.py" >/dev/null 2>&1 && break
    done
    [ -x "$SHARE_DIR/venv/bin/pip" ] || die "bootstrap pip failed; install python3-venv then retry"
fi

info "Installing PyQt6 and yt-dlp from PyPI (one-time download) ..."
"$SHARE_DIR/venv/bin/pip" install --upgrade pip >/dev/null
"$SHARE_DIR/venv/bin/pip" install "$WORK" >&2 || die "pip install of ytdownloader failed"
# pyproject declares yt-dlp, but re-resolve it explicitly so the app always
# gets the *newest* release from PyPI rather than whatever a cached wheel
# happened to carry.
"$SHARE_DIR/venv/bin/pip" install --upgrade yt-dlp >&2 \
    || die "pip install of yt-dlp failed"
info "   yt-dlp: $("$SHARE_DIR/venv/bin/yt-dlp" --version 2>/dev/null || echo 'installed (version unknown)')"

# ---------------------------------------------------------------- ffmpeg
FFMPEG_DL_WARNING=""
if [ "$WITH_FFMPEG_DL" = "yes" ]; then
    ARCH="$(uname -m)"
    NEED_DL=""
    if ! command -v ffmpeg >/dev/null 2>&1; then
        NEED_DL="no system ffmpeg"
    fi
    if [ -n "$NEED_DL" ] && [ "$ARCH" = "x86_64" ]; then
        URL="https://johnvansickle.com/ffmpeg/releases/ffmpeg-release-amd64-static.tar.xz"
        info "ffmpeg not found; downloading a static build for x86_64 ..."
        mkdir -p "$SHARE_DIR/bin"
        for getter in curl wget; do
            command -v "$getter" >/dev/null 2>&1 || continue
            case "$getter" in
                curl) curl -fsSL "$URL" -o "$WORK/ffmpeg.tar.xz" && break ;;
                wget) wget -qO "$WORK/ffmpeg.tar.xz" "$URL" && break ;;
            esac
        done
        if [ -s "$WORK/ffmpeg.tar.xz" ] && mkdir -p "$WORK/ffm" \
           && tar -xJf "$WORK/ffmpeg.tar.xz" -C "$WORK/ffm" 2>/dev/null; then
            found_any=""
            for tool in ffmpeg ffprobe; do
                src="$(find "$WORK/ffm" -type f -name "$tool" | head -n 1)"
                if [ -n "$src" ]; then
                    mv "$src" "$SHARE_DIR/bin/$tool" && chmod +x "$SHARE_DIR/bin/$tool"
                    found_any="yes"
                fi
            done
            [ -n "$found_any" ] || FFMPEG_DL_WARNING="static ffmpeg download did not contain the usual binaries"
        else
            FFMPEG_DL_WARNING="could not download the static ffmpeg build"
        fi
    elif [ -n "$NEED_DL" ]; then
        FFMPEG_DL_WARNING="ffmpeg is required but ffmpeg auto-download only supports x86_64 (you have $ARCH)"
    fi
fi
if ! command -v ffmpeg >/dev/null 2>&1 && [ ! -x "$SHARE_DIR/bin/ffmpeg" ]; then
    die "ffmpeg is required (audio extraction / video merging).${FFMPEG_DL_WARNING:+ ($FFMPEG_DL_WARNING)} Install it with your package manager, or rerun without --no-ffmpeg."
fi

# ---------------------------------------------------------------- launcher
mkdir -p "$BIN_DIR"
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env bash
# generated by ytdownloader installer ${VERSION}
export YTDOWNLOADER_HOME="${SHARE_DIR}"
export PATH="${SHARE_DIR}/bin:${SHARE_DIR}/venv/bin:$PATH"
exec "${SHARE_DIR}/venv/bin/python" -m yt_downloader "\$@"
LAUNCH
chmod +x "$LAUNCHER"

# ---------------------------------------------------------------- desktop
mkdir -p "$DESKTOP_DIR"
sed "s|^Exec=.*|Exec=$LAUNCHER|" \
    "$WORK/yt_downloader.desktop" > "$DESKTOP_FILE"
command -v update-desktop-database >/dev/null 2>&1 \
    && update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true

info "Installed ytdownloader ${VERSION}."
info "   app data : $SHARE_DIR"
info "   launcher : $LAUNCHER (on PATH if ${BIN_DIR} is in PATH)"
info "   desktop  : $DESKTOP_FILE"
[ -n "$FFMPEG_DL_WARNING" ] && info "note: $FFMPEG_DL_WARNING"
# Prefer the bare command only when this install's bin dir is actually on
# PATH; otherwise name the launcher we just wrote (command -v would happily
# return some *other* copy of ytdownloader found elsewhere on the system).
START="$LAUNCHER"
case ":$PATH:" in
    *":$BIN_DIR:"*) START="$APP_ID" ;;
esac
info "Run it with: $START   (or find “YouTube Downloader” in your app menu)"
info "Desktop-file cache: some file managers need a re-login to show the entry."
info "Existing downloads/state (if this is an upgrade) are preserved."
exit 0

__YTD_PAYLOAD_BELOW__
'''

# Everything after the marker above is replaced with the real payload base64.


def build_installer() -> str:
    version = read_version()
    payload = build_payload()
    b64 = base64.b64encode(payload).decode("ascii")

    header = INSTALLER_TEMPLATE.replace("@VERSION@", version)
    # Keep only up to (and including) the marker line; append payload.
    idx = header.rindex(PAYLOAD_MARKER) + len(PAYLOAD_MARKER)
    header = header[:idx]
    out_name = ROOT / f"ytdownloader-{version}-linux-installer.sh"
    out_name.write_text(header + "\n" + b64 + "\n", encoding="utf-8")
    os.chmod(out_name, 0o755)
    print(f"Built {out_name.name} ({out_name.stat().st_size} bytes) version {version}")
    return out_name.name


if __name__ == "__main__":
    build_installer()
